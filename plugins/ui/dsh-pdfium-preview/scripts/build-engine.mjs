
// Build client.pdfium.js — the lazy engine chunk for dsh-pdfium-preview.
// Source: @hyzyla/pdfium 3.0.0 dist/index.esm.js (MIT wrapper) + dist/pdfium.wasm (PDFium, BSD-3)
// Output: a window.__ModuleLoader__ factory chunk (script, not ESM) exporting PDFiumLibrary.
import fs from 'node:fs';
import path from 'node:path';

const PKG = process.env.PDFIUM_PKG_DIR || 'D:/DeepSeek-Workspace/.tmp/pdfium-3.0.0/package';
const dist = path.join(PKG, 'dist');
const out = process.argv[2] || path.join(import.meta.dirname, '..', 'client.pdfium.js');

let glue = fs.readFileSync(path.join(dist, 'index.esm.js'), 'utf8');
const wasmB64 = fs.readFileSync(path.join(dist, 'pdfium.wasm')).toString('base64');

if (/^export default/m.test(glue)) throw new Error('unexpected default export');

// 1. kill the ES-module-only constructs that cannot appear in a classic script
glue = glue.replaceAll('import.meta.url', '"about:blank"');
glue = glue.replace('const nodeModule = await import("node:module");', 'const nodeModule = undefined;');
// the chunk always runs in a window; keep the emscripten node branch unreachable so the
// classic-script build also behaves identically when exercised from a node harness
glue = glue.replace(
  'var ENVIRONMENT_IS_NODE = globalThis.process?.versions?.node && globalThis.process?.type != "renderer";',
  'var ENVIRONMENT_IS_NODE = !globalThis.window && globalThis.process?.versions?.node && globalThis.process?.type != "renderer";'
);
// 2. ESM export block -> CommonJS assignments
glue = glue.replace(/^export\s*\{([^}]*)\};?/m, (_m, names) => {
  return names
    .split(',')
    .map((n) => n.trim())
    .filter(Boolean)
    .map((n) => (n.includes(' as ') ? n.split(/\s+as\s+/) : [n, n]))
    .map(([local, exported]) => `exports.${exported.trim()} = ${local.trim()};`)
    .join('\n');
});
if (/^\s*(import|export)\s/m.test(glue)) throw new Error('ESM syntax left in glue');

// 3. wasm base64 payload (the /plugins route can only serve client.*.js, so the wasm travels inline)
const header = [
  '//! dsh-pdfium-preview engine chunk — generated by scripts/build-engine.mjs, do not edit by hand.',
  '//! @hyzyla/pdfium 3.0.0 (MIT) + PDFium (BSD-3-Clause, Copyright 2014 PDFium Authors).',
  '//! Sources: https://github.com/hyzyla/pdfium  https://pdfium.googlesource.com/pdfium/',
  ''
].join('\n');

const body = [
  header,
  'window.__ModuleLoader__.load({',
  '  id: "dsh-pdfium-preview/client.pdfium.js",',
  '  factory: (_require) => {',
  '    "use strict";',
  '    var module = { exports: {} };',
  '    var exports = module.exports;',
  '    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });',
  '    var PDFIUM_WASM_BASE64 = "' + wasmB64 + '";',
  '    function __dshBase64ToBytes(b64) {',
  '      var bin = atob(b64);',
  '      var bytes = new Uint8Array(bin.length);',
  '      for (var i = 0; i < bin.length; i += 1) bytes[i] = bin.charCodeAt(i);',
  '      return bytes;',
  '    }',
  glue,
  '    exports.__wasmBytes = function () { return __dshBase64ToBytes(PDFIUM_WASM_BASE64); };',
  '    return module.exports;',
  '  },',
  '});',
  ''
].join('\n');

try {
  // authoritative check: the chunk must compile as a classic script
  new Function(body);
} catch (error) {
  throw new Error('generated chunk does not compile as a classic script: ' + error.message);
}
fs.writeFileSync(out, body);
console.log('wrote', out, body.length, 'bytes');
